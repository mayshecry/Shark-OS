#!/usr/bin/env python3
"""Embed docs/router_ui.html into src/net/router_ui_html.h.

The management console is a single self-contained HTML file (inline CSS/JS,
no external assets) so it can be served straight from the kernel's TCP
stack and also previewed offline in a browser.

Usage: python3 tools/gen_router_ui.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs" / "router_ui.html"
TARGET = ROOT / "src" / "net" / "router_ui_html.h"


def main() -> None:
    html = SOURCE.read_text(encoding="utf-8")
    lines = html.splitlines(keepends=True)
    out = [
        "/* Generated by tools/gen_router_ui.py from docs/router_ui.html.",
        "   Do not edit this file by hand. */",
        "#ifndef SHARKOS_ROUTER_UI_HTML_H",
        "#define SHARKOS_ROUTER_UI_HTML_H",
        "",
        "static const char ROUTER_UI_HTML[] =",
    ]
    for index, line in enumerate(lines):
        encoded = json.dumps(line, ensure_ascii=True).replace("\\u00a0", " ")
        out.append(f"    {encoded}" + (";" if index == len(lines) - 1 else ""))
    out += [
        "",
        "static const unsigned int ROUTER_UI_HTML_LEN = sizeof(ROUTER_UI_HTML) - 1;",
        "",
        "#endif",
        "",
    ]
    TARGET.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(html)} bytes of HTML)")


if __name__ == "__main__":
    main()
